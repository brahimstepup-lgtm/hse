    fun tr(fr: String, vararg args: Any?): String {
        val base = when (lang) {
            "en" -> dict[fr]?.first ?: fr
            "ar" -> dict[fr]?.second ?: fr
            else -> fr
        }
        var out = base
        args.forEachIndexed { i, a -> out = out.replace("{$i}", a?.toString() ?: "") }
        return out
    }

